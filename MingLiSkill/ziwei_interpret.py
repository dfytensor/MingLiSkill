def query_ziwei_interpret(ziwei_palaces, palace_zhi_map=None):
    """根据紫微排盘返回相关断语。
    ziwei_palaces: {宫名: [星名列表]}
    palace_zhi_map: {宫名: 地支} (可选，用于亮度)
    返回: [(匹配描述, 来源)]"""
    out = []
    
    # 1. 单星入宫
    for palace, stars in ziwei_palaces.items():
        for star in stars:
            if star in STAR_IN_PALACE:
                palace_interp = STAR_IN_PALACE[star].get(palace, '')
                if palace_interp:
                    out.append(('%s入%s：%s' % (star, palace, palace_interp), '星曜宫位'))
    
    # 2. 双星组合
    for palace, stars in ziwei_palaces.items():
        if len(stars) >= 2:
            for i in range(len(stars)):
                for j in range(i+1, len(stars)):
                    combo = (stars[i], stars[j])
                    if combo in STAR_COMBO:
                        out.append(('%s+%s在%s：%s' % (stars[i], stars[j], palace, STAR_COMBO[combo]), '双星组合'))
                    combo_rev = (stars[j], stars[i])
                    if combo_rev in STAR_COMBO:
                        out.append(('%s+%s在%s：%s' % (stars[j], stars[i], palace, STAR_COMBO[combo_rev]), '双星组合'))
    
    # 3. 星曜本性
    for palace, stars in ziwei_palaces.items():
        for star in stars:
            if star in STAR_NATURE:
                out.append(('%s（%s宫）：%s' % (star, palace, STAR_NATURE[star]), '星曜本性'))
    
    return out
