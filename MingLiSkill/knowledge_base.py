def query_kb(features, top_n=6):
    """features: dict with keys 任选:
       十神: list[str]  女命十神/男命十神: list[str]
       力量: list[str]  神煞: list[str]  结构: list[str]
       五行: list[str]  流年: list[str]  宫位: list[str]
    Returns list of (hits_count, entry)."""
    results = []
    for e in KB:
        hits = 0
        trig = e["触发"]
        for k, vals in trig.items():
            fv = features.get(k, [])
            if isinstance(fv, str):
                fv = [fv]
            for v in vals:
                if v in fv:
                    hits += 1
                    break
        if hits > 0:
            results.append((hits, e))
    results.sort(key=lambda x: -x[0])
    return results[:top_n]


def format_kb_results(results):
    out = []
    for hits, e in results:
        out.append("[%s|命中%d] %s → 应事: %s" % (e["主题"], hits, e["断语"], e["关键词"][:5]))
    return out
